package org.eclipse.kura.example.remoteservice.api;

public class SumRequest {

    private final int a;
    private final int b;

    public SumRequest(int a, int b) {
        this.a = a;
        this.b = b;
    }

    public int getA() {
        return a;
    }

    public int getB() {
        return b;
    }

}
